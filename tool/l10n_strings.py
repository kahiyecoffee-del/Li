def build(lang_index, locale):
    arb = {'@@locale': locale}
    for key, (en, tr, ph) in S.items():
        arb[key] = en if lang_index == 0 else tr
        if lang_index == 0:
            meta = {}
            if ph:
                meta['placeholders'] = {k: {'type': v} for k, v in ph.items()}
            # Validate that placeholders appear in both translations.
            for k in ph:
                assert '{' + k in en and '{' + k in tr, f'{key}: placeholder {k} missing'
            if meta:
                arb['@' + key] = meta
    return arb

root = os.path.join(os.path.dirname(__file__), '..', 'lib', 'l10n')
os.makedirs(root, exist_ok=True)
for i, loc in enumerate(['en', 'tr']):
    with open(os.path.join(root, f'app_{loc}.arb'), 'w', encoding='utf-8') as f:
        json.dump(build(i, loc), f, ensure_ascii=False, indent=2)
        f.write('\n')

# Overrides for every string that mentions Lio, so users can rename the
# assistant (lib/l10n/named_localizations.dart, used by NamedLocalizationsDelegate).
def dart_named():
    keys = [(k, ph) for k, (en, tr, ph) in S.items() if 'Lio' in en or 'Lio' in tr]
    out = ["// GENERATED by tool/l10n_strings.py — do not edit.",
           "// ignore_for_file: annotate_overrides, type=lint",
           "import 'package:flutter/foundation.dart';",
           "import 'package:flutter/widgets.dart';",
           "",
           "import '../core/l10n/assistant_name.dart';",
           "import 'gen/app_localizations.dart';",
           "import 'gen/app_localizations_en.dart';",
           "import 'gen/app_localizations_tr.dart';",
           ""]
    def members(tr):
        lines = []
        for k, ph in keys:
            if ph:
                params = ', '.join(f"{t} {n}" for n, t in ph.items())
                args = ', '.join(ph.keys())
                lines.append(f"  @override String {k}({params}) => _r(super.{k}({args}));")
            else:
                lines.append(f"  @override String get {k} => _r(super.{k});")
        return lines
    for cls, base, tr in [('_NamedEn', 'AppLocalizationsEn', 'false'), ('_NamedTr', 'AppLocalizationsTr', 'true')]:
        out.append(f"class {cls} extends {base} {{")
        out.append(f"  {cls}(this.assistant);")
        out.append("  final String assistant;")
        out.append(f"  String _r(String s) => renameAssistant(s, assistant, turkish: {tr});")
        out += members(tr)
        out.append("}")
        out.append("")
    out += [
        "/// App strings with the user's name for the assistant instead of \"Lio\".",
        "class NamedLocalizationsDelegate extends LocalizationsDelegate<AppLocalizations> {",
        "  const NamedLocalizationsDelegate(this.assistant);",
        "  final String assistant;",
        "",
        "  @override",
        "  bool isSupported(Locale locale) => AppLocalizations.delegate.isSupported(locale);",
        "",
        "  @override",
        "  Future<AppLocalizations> load(Locale locale) {",
        "    final base = lookupAppLocalizations(locale);",
        "    if (assistant.trim().isEmpty || assistant == 'Lio') return SynchronousFuture(base);",
        "    return SynchronousFuture(base.localeName.startsWith('tr') ? _NamedTr(assistant) : _NamedEn(assistant));",
        "  }",
        "",
        "  @override",
        "  bool shouldReload(NamedLocalizationsDelegate old) => old.assistant != assistant;",
        "}",
        "",
    ]
    with open(os.path.join(root, 'named_localizations.dart'), 'w', encoding='utf-8') as f:
        f.write('\n'.join(out))

