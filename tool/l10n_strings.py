def build(lang_index, locale):
    arb = {'@@locale': locale}
    for key, (en, tr, ph) in S.items():
        arb[key] = en if lang_index == 0 else tr
        if lang_index == 0:
            meta = {}
            if ph:
                meta['placeholders'] = {k: {'type': v} for k, v in ph.items()}
            # Validate that placeholders appear in both translations.
            for k in ph:
                assert '{' + k in en and '{' + k in tr, f'{key}: placeholder {k} missing'
            if meta:
                arb['@' + key] = meta
    return arb

root = os.path.join(os.path.dirname(__file__), '..', 'lib', 'l10n')
os.makedirs(root, exist_ok=True)
for i, loc in enumerate(['en', 'tr']):
    with open(os.path.join(root, f'app_{loc}.arb'), 'w', encoding='utf-8') as f:
        json.dump(build(i, loc), f, ensure_ascii=False, indent=2)
        f.write('\n')
print(f'{len(S)} strings written')
